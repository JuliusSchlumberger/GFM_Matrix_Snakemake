"""Run the SFINCS binary as a subprocess with streamed output and a timeout.

Adapted from the basin-scale SFINCS workflow's sfincs_run.py.
"""

from __future__ import annotations

import os
import subprocess
import sys
import threading
from pathlib import Path


def run_sfincs_subprocess(
    sfincs_exe: str | Path,
    cwd: str | Path,
    timeout_s: float,
    log,
    label: str = "SFINCS run",
    n_threads: int | None = None,
) -> None:
    """Run SFINCS in ``cwd``, forwarding stdout/stderr to ``log`` and stderr live.

    Relative file references in sfincs.inp resolve against ``cwd``. ``n_threads``
    sets OMP_NUM_THREADS for the subprocess only (SFINCS defaults to 1; None/0
    leaves the env unchanged). Raises RuntimeError on timeout or non-zero exit.
    """
    sfincs_exe = Path(sfincs_exe).resolve()
    log.info(f"Running {label}: {sfincs_exe}")

    env = None
    if n_threads:
        env = os.environ.copy()
        env["OMP_NUM_THREADS"] = str(int(n_threads))
        log.info(f"{label}: OMP_NUM_THREADS={n_threads}")

    proc = subprocess.Popen(
        [str(sfincs_exe)],
        cwd=str(cwd),
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
        bufsize=1,
        env=env,
    )

    def _forward(pipe, log_fn):
        for line in pipe:
            line = line.rstrip()
            if line:
                log_fn(f"[sfincs] {line}")
                print(f"[sfincs] {line}", file=sys.stderr, flush=True)

    t_out = threading.Thread(target=_forward, args=(proc.stdout, log.info))
    t_err = threading.Thread(target=_forward, args=(proc.stderr, log.warning))
    t_out.start()
    t_err.start()

    # proc.wait() must run before joining the reader threads, or the timeout
    # is unreachable (join() blocks until SFINCS's pipes close on exit).
    try:
        proc.wait(timeout=timeout_s)
    except subprocess.TimeoutExpired:
        proc.kill()
        t_out.join()
        t_err.join()
        raise RuntimeError(f"{label} exceeded {timeout_s}s timeout")

    t_out.join()
    t_err.join()

    if proc.returncode != 0:
        raise RuntimeError(f"{label} failed with exit code {proc.returncode}")
