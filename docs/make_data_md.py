"""Write docs/data.md, the input-dataset table, from the two data catalogs.

Usage: python docs/make_data_md.py
"""

from __future__ import annotations

import re
from pathlib import Path

import yaml

REPO = Path(__file__).resolve().parents[1]
CONFIG_DIR = REPO / "snakemake_workflow" / "config"
OUT = REPO / "docs" / "data.md"

# (catalog file, placeholder its relative `path:` entries resolve against)
CATALOGS = [
    ("data_catalog_gfm.yml", "<data_root>"),
    ("data_catalog_validation.yml", "<benchmark_root>"),
]

HEADER = """# Input data

Generated by `docs/make_data_md.py` from the two data catalogs; edit the catalogs and rerun
the script instead of editing this file.

- `snakemake_workflow/config/data_catalog_gfm.yml`: paths resolve relative to `paths.root` (`<data_root>`).
- `snakemake_workflow/config/data_catalog_validation.yml`: paths resolve relative to
  `validation.benchmark_root` (`<benchmark_root>`, default `<data_root>/inputs/validation`).

The data root layout follows the catalogs' `path:` entries (the Path column). Authors, papers,
vertical references and field descriptions are in each entry's `meta` block.
"""

COLUMNS = ["Dataset", "Description", "Version", "Source", "Licence", "Access", "Path"]


def _first_sentence(text: str) -> str:
    text = " ".join(str(text).split())
    match = re.match(r"(.+?(?<!\bal)(?<!\be\.g)(?<!\bi\.e)[.!?])(\s|$)", text)
    return match.group(1) if match else text


def _cell(value) -> str:
    return " ".join(str(value).split()).replace("|", r"\|") if value is not None else ""


def _row(key: str, entry: dict, root: str) -> str:
    meta = entry.get("meta", {})
    url = meta.get("source_url", "")
    author = _cell(meta.get("source_author", url))
    cells = [
        f"`{key}`",
        _cell(_first_sentence(meta.get("description", ""))),
        _cell(meta.get("source_version")),
        f"[{author}]({url})" if url else author,
        _cell(meta.get("source_license")),
        _cell(meta.get("source_access")),
        f"`{root}/{entry.get('path', '')}`",
    ]
    return "| " + " | ".join(cells) + " |"


def main() -> None:
    lines = [HEADER, "| " + " | ".join(COLUMNS) + " |", "|" + "---|" * len(COLUMNS)]
    for filename, root in CATALOGS:
        catalog = yaml.safe_load((CONFIG_DIR / filename).read_text(encoding="utf-8"))
        lines += [_row(key, entry, root) for key, entry in catalog.items()]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
