"""Run the flood model for a single tile/return_period/waterlevel_name,
from a plain CLI call instead of a Snakemake `script:` invocation.

Used by the sbatch scripts generated by generate_aqueduct_jobs.py, one call
per (tile_id, return_period, waterlevel_name) - see that script and
hpc_dispatch.smk's generate_aqueduct_jobs rule for context. Reuses the exact
same skip/OOM-catch/placeholder logic as scripts/run_aqueduct.py, including
the wave-0 empty-boundaries check (2026-08 - previously done as a SEPARATE
pre-check pass at generation time instead, reading every wave-0 tile's
boundaries file again here on generation; found live 2026-08-10 to cost
~110,000 individual file reads, ~90min, for no benefit over just checking
`.empty` on the SAME read this script already needs to do for a real,
non-empty scenario - exactly what run_aqueduct.py already did natively,
this script had just drifted from it). Keep this in sync with
run_aqueduct.py.

Usage:
    python run_aqueduct_cli.py --config <resolved_config.yml>
        --tile-id <id> --return-period <RP..> --waterlevel-name <SLR_..>
"""

import argparse
import os
import shutil
import sys
import time
from pathlib import Path

import geopandas as gpd
import rasterio
import yaml

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src"))

from aqueduct_runner import (  # noqa: E402
    NO_STATIONS_REASON,
    NO_UPSTREAM_FLOODING_REASON,
    log_run_timing,
    log_skipped_tile,
    mark_tile_oom,
    run_aqueduct_python,
    tile_marked_oom,
    write_zero_waterdepth,
)
from boundaries import collect_neighbor_wave_seeds  # noqa: E402
from config_utils import path_ready, retry_transient_io  # noqa: E402
from rasters import save_nodata_raster  # noqa: E402
from tiles import load_tile_grid  # noqa: E402


def _output_already_done(output_path: str) -> bool:
    """Whether `output_path` already exists and is a genuinely readable
    raster - not just a bare existence check, since a job killed mid-write
    (SLURM time limit, node failure/preemption) can leave a truncated file
    behind that `os.path.exists` alone would wrongly treat as complete.

    Reading one pixel is enough to force GDAL to validate the file's
    structure without paying the cost of decoding the whole raster.
    """
    if not path_ready(output_path):
        return False
    try:
        with rasterio.open(output_path) as src:
            src.read(1, window=((0, 1), (0, 1)))
        return True
    except Exception:
        return False


def _stage_file_locally(src_path: str) -> str:
    """Copy `src_path` to node-local scratch and return the local copy's
    path, instead of opening it straight off P:\\.

    Added 2026-10-14: confirmed live that GDAL/OGR's SQLite lock
    acquisition - needed just to OPEN a GeoPackage, even read-only - can
    hang indefinitely on a Hydrax compute node reading P:\\ directly, for a
    single, non-concurrent read (not a lock-contention/concurrency issue -
    see generate_aqueduct_jobs.py's `_stage_tile_grid_lines` docstring,
    which fixes the same problem for the shared tile_grid.gpkg). A plain
    content copy (`shutil.copy2`, no GDAL/SQLite involved) does not hit that
    lock path and completes normally. Unlike the tile grid - one file,
    shared by a whole batch, staged once in the sbatch script itself -
    `boundaries_{scenario}.gpkg` differs per (tile, rp, slr) triple, so it's
    staged here, per-invocation; caller is responsible for deleting the
    returned path once done with it.
    """
    stage_dir = os.path.join(os.environ.get("TMPDIR", "/tmp"), "gfm_staged_inputs")
    os.makedirs(stage_dir, exist_ok=True)
    dst = os.path.join(stage_dir, f"{os.getpid()}_{os.path.basename(src_path)}")
    retry_transient_io(shutil.copy2, src_path, dst)
    return dst


def main() -> None:
    """Run this script: solve (or skip/placeholder) one (tile, rp, slr) combo.

    Parses --config/--tile-id/--return-period/--waterlevel-name, then either
    returns early (output already done, or tile pre-marked OOM - writing a
    nodata placeholder in the OOM case), writes a zero-waterdepth placeholder
    when this scenario has no boundaries/no upstream flooding to seed from, or
    runs the real flood solve and writes `waterdepth_{rp}_{slr}.tif`. Always
    logs a run-timing record (see module docstring) except on the
    already-done early return.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", required=True, help="Path to a fully-resolved config.yml (e.g. resolved_config.yml)")
    parser.add_argument("--tile-id", required=True)
    parser.add_argument("--return-period", required=True)
    parser.add_argument("--waterlevel-name", required=True)
    args = parser.parse_args()
    start = time.perf_counter()

    with open(args.config, encoding="utf-8") as f:
        config = yaml.safe_load(f)

    model_outputs = config["simulation"]["model_outputs"]
    # See preprocessing.smk's own comment - defaults to model_outputs (no-op
    # unless a scenario config sets it, e.g. the ESP/FRA/NOR calibration
    # sweep, which points it at a group-shared directory since none of the
    # 14 sweep points change anything preprocessing produces).
    preprocessing_inputs_dir = config["simulation"].get("preprocessing_inputs_dir") or model_outputs
    raster_config = config["raster_format"]
    flooding_config = config["simulation"]["flooding"]
    ocean_code = config["tile_generation"]["ocean_code"]
    river_code = config["tile_generation"]["river_code"]
    tile_grid_path = config["tile_grid"]["path"]

    tile_id = args.tile_id
    scenario_name = f"{args.return_period}_{args.waterlevel_name}"
    tile_dir = os.path.join(model_outputs, tile_id)
    inputs_dir = os.path.join(preprocessing_inputs_dir, tile_id, "inputs")
    dem_path = os.path.join(inputs_dir, "dem.tif")
    mask_path = os.path.join(inputs_dir, "mask.tif")
    friction_path = os.path.join(inputs_dir, "friction.tif")
    boundaries_path = os.path.join(inputs_dir, f"boundaries_{scenario_name}.gpkg")
    output_path = os.path.join(tile_dir, "results", f"waterdepth_{scenario_name}.tif")
    skipped_dir = os.path.join(model_outputs, "skipped_tiles")
    oom_dir = os.path.join(model_outputs, "oom_tiles")

    # Idempotency: unlike run_aqueduct.py (which gets this for free from
    # Snakemake's own output-tracking), this standalone CLI has no built-in
    # "already done" check - added 2026-08 so a resumed/rebalanced dispatch
    # (regenerated job list covering only what's still missing) is also
    # safe to run even if a job for an already-complete (tile, rp, slr)
    # somehow gets submitted again, instead of silently redoing real,
    # already-correct work.
    timings_dir = os.path.join(model_outputs, "run_timings")

    if _output_already_done(output_path):
        # No log_run_timing call here - this (tile, rp, slr) was already solved in
        # some EARLIER invocation (that's what "already done" means), which already
        # wrote the real timing record for it; writing a near-zero entry now would
        # silently overwrite that real data with this idempotency check's own trivial
        # elapsed time.
        return

    if tile_marked_oom(oom_dir, tile_id):
        log_skipped_tile(
            skipped_dir, tile_id, scenario_name,
            reason="tile too large (out-of-memory on a previous return period/SLR scenario for this tile)",
        )
        save_nodata_raster(dem_path, output_path, raster_config)
        log_run_timing(
            timings_dir, tile_id, args.return_period, args.waterlevel_name,
            elapsed_s=time.perf_counter() - start,
            obstacle_coupling_diagnostics={"outcome": "oom_premarked"},
        )
        return

    tile_grid = load_tile_grid(tile_grid_path)
    this_tile = tile_grid[tile_grid["tile_id"] == int(tile_id)]
    hop_distance = int(this_tile["hop_distance"].iloc[0])

    # Resolve this scenario's forcing - mirrors run_aqueduct.py's own
    # skip_reason pattern exactly (2026-08 - this script previously relied
    # on wave-0 empty-boundaries jobs being filtered out at generation time
    # instead, via a separate upfront pass that re-read every wave-0 tile's
    # boundaries file again; see module docstring for why that was removed).
    seed_rows = seed_cols = seed_values = None
    skip_reason = None
    local_boundaries_path = None

    try:
        if hop_distance == 0:
            # Staged to node-local scratch, not read straight off P:\ - see
            # `_stage_file_locally`'s own docstring: GDAL/OGR's SQLite lock
            # acquisition on opening a gpkg can hang indefinitely on a Hydrax
            # compute node even for a single, non-concurrent read, while a
            # plain content copy does not.
            local_boundaries_path = _stage_file_locally(boundaries_path)
            boundaries = retry_transient_io(gpd.read_file, local_boundaries_path)
            if boundaries.empty:
                skip_reason = NO_STATIONS_REASON
        else:
            this_geom = this_tile.geometry.iloc[0]
            candidates = tile_grid[
                (tile_grid["hop_distance"] < hop_distance)
                & (tile_grid["tile_id"] != int(tile_id))
                & tile_grid.geometry.intersects(this_geom)
            ]
            available = []
            for cand_id in candidates["tile_id"]:
                cand_dem = os.path.join(preprocessing_inputs_dir, str(int(cand_id)), "inputs", "dem.tif")
                cand_mask = os.path.join(preprocessing_inputs_dir, str(int(cand_id)), "inputs", "mask.tif")
                cand_waterdepth = os.path.join(
                    model_outputs, str(int(cand_id)), "results", f"waterdepth_{scenario_name}.tif",
                )
                # path_ready, not bare os.path.exists (which swallows I/O errors
                # and returns False without ever retrying) - on the HPC's
                # network-mounted P:\ share, a transient blip here would
                # otherwise be silently indistinguishable from "neighbour
                # genuinely hasn't run yet", converting into a wrongly-confident
                # real-zero result instead of the correct flooded one.
                if path_ready(cand_dem) and path_ready(cand_mask) and path_ready(cand_waterdepth):
                    available.append((cand_dem, cand_mask, cand_waterdepth))
            seed_rows, seed_cols, seed_values = collect_neighbor_wave_seeds(dem_path, available)
            if len(seed_rows) == 0:
                skip_reason = NO_UPSTREAM_FLOODING_REASON

        if skip_reason is not None:
            log_skipped_tile(skipped_dir, tile_id, scenario_name, reason=skip_reason)
            write_zero_waterdepth(dem_path, output_path)
            log_run_timing(
                timings_dir, tile_id, args.return_period, args.waterlevel_name,
                elapsed_s=time.perf_counter() - start,
                obstacle_coupling_diagnostics={"outcome": "skip_no_inundation", "skip_reason": skip_reason},
            )
            return

        oc_config = flooding_config.get("obstacle_coupling", {})
        try:
            diagnostics = run_aqueduct_python(
                dem_path, mask_path, friction_path, output_path,
                resolution=flooding_config["resolution"], k=flooding_config["knn"],
                variable=args.waterlevel_name,
                boundaries_path=None if hop_distance >= 1 else local_boundaries_path,
                seed_rows=seed_rows, seed_cols=seed_cols, seed_values=seed_values,
                ocean_code=ocean_code, river_code=river_code,
                obstacle_coupling=oc_config.get("enabled", False),
                max_outer_iterations=oc_config.get("max_outer_iterations", 3),
                max_rounds=flooding_config["max_rounds"],
                outer_convergence_pct=oc_config.get("outer_convergence_pct", 0.01),
                waterlevel_epsilon_m=flooding_config["waterlevel_epsilon_m"],
                friction_scale_factor=flooding_config.get("friction_scale_factor", 1.0),
            )
        except MemoryError:
            mark_tile_oom(oom_dir, tile_id, reason="MemoryError in flood_depth_dense - tile too large")
            log_skipped_tile(skipped_dir, tile_id, scenario_name, reason="MemoryError - tile too large")
            save_nodata_raster(dem_path, output_path, raster_config)
            log_run_timing(
                timings_dir, tile_id, args.return_period, args.waterlevel_name,
                elapsed_s=time.perf_counter() - start,
                obstacle_coupling_diagnostics={"outcome": "oom"},
            )
        else:
            log_run_timing(
                timings_dir, tile_id, args.return_period, args.waterlevel_name,
                elapsed_s=time.perf_counter() - start,
                obstacle_coupling_diagnostics={"outcome": "solved", **diagnostics},
            )
    finally:
        if local_boundaries_path is not None:
            try:
                os.remove(local_boundaries_path)
            except OSError:
                pass


if __name__ == "__main__":
    main()
